def dedupe_similar_pairs(pairs: list[tuple[str, str]]) -> list[tuple[str, str]]:
    seen: set[str] = set()
    result: list[tuple[str, str]] = []
    for insider, mismatch in pairs:
        a = insider.casefold().strip()
        b = mismatch.casefold().strip()
        if not a or not b or a == b:
            continue
        if a in seen or b in seen:
            continue
        seen.add(a)
        seen.add(b)
        result.append((insider.strip(), mismatch.strip()))
    return result


def letters_only(value: str) -> str:
    return "".join(ch for ch in value.casefold() if ch.isalpha())


def has_sequel_mark(value: str) -> bool:
    return re.search(r"\b(\d+|ii|iii|iv|vi|vii|viii|ix|xi|xii)\b", value.casefold()) is not None


def sequel_stem(value: str) -> str:
    letters = letters_only(value)
    for suffix in ("xii", "viii", "vii", "iii", "ii", "iv", "vi", "ix", "xi"):
        if letters.endswith(suffix) and len(letters) > len(suffix) + 2:
            return letters[: -len(suffix)]
    return letters


def is_numbered_sequel(left: str, right: str) -> bool:
    if not has_sequel_mark(left) and not has_sequel_mark(right):
        return False
    left_stem = sequel_stem(left) if has_sequel_mark(left) else letters_only(left)
    right_stem = sequel_stem(right) if has_sequel_mark(right) else letters_only(right)
    return bool(left_stem) and left_stem == right_stem


def edit_distance(left: str, right: str) -> int:
    previous = list(range(len(right) + 1))
    for i, left_char in enumerate(left, start=1):
        current = [i]
        for j, right_char in enumerate(right, start=1):
            current.append(min(
                previous[j] + 1,
                current[j - 1] + 1,
                previous[j - 1] + (left_char != right_char),
            ))
        previous = current
    return previous[-1]


def is_lookalike(left: str, right: str) -> bool:
    if is_numbered_sequel(left, right):
        return False
    a = letters_only(left)
    b = letters_only(right)
    if not a or not b or a == b:
        return False
    shorter = min(len(a), len(b))
    if shorter < 5:
        return False
    distance = edit_distance(a, b)
    shared_prefix = 0
    for left_char, right_char in zip(a, b):
        if left_char != right_char:
            break
        shared_prefix += 1
    return distance == 1 or (distance == 2 and shorter >= 8 and shared_prefix >= 3)


def validate_pairs(pairs: list[tuple[str, str]], target: int = 543) -> None:
    if len(pairs) < target:
        raise ValueError(f"Need {target} pairs, got {len(pairs)}")

    seen_words: set[str] = set()
    for a, b in pairs[:target]:
        if is_lookalike(a, b):
            raise ValueError(f"Words are too similar: {a} / {b}")
        for word in (a, b):
            key = word.casefold().strip()
            if key in seen_words:
                raise ValueError(f"Repeated title: {word}")
            seen_words.add(key)


def build_pairs(target: int = 543) -> list[tuple[str, str]]:
    pairs = dedupe_similar_pairs(SIMILAR_PAIRS)
    if len(pairs) < target:
        raise ValueError(f"Need {target} similar pairs after dedupe, got {len(pairs)}")
    selected = pairs[:target]
    validate_pairs(selected, target)
    return selected


def main() -> None:
    pairs = build_pairs(543)
    out_dir = Path(__file__).resolve().parent
    payload = [{"insider": a, "mismatch": b} for a, b in pairs]
    out_path = out_dir / "indian_pop_culture_pairs.json"
    out_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(pairs)} similar pairs to {out_path.name}")


